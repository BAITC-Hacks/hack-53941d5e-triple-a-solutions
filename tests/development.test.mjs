test('local progress survives reload and ignores corrupt or different dataset data', () => {
  let value; const storage = { getItem: () => value, setItem: (key, data) => { assert.equal(key, STORAGE_KEY); value = data; } };
  const restored = restoreProgress(fixture, storage), model = restored.model;
  const plan = buildDevelopmentPaths(fixture, model.snapshot(person))[0];
  model.complete(person.employee_id, 'FOUNDATION');
  assert.equal(saveProgress(fixture, model, { ...restored, plans: { SYNTHETIC: { source: 'rules', plan } } }, storage), true);
  const next = restoreProgress(fixture, storage);
  assert.deepEqual(next.model.snapshot(person).simulated, ['FOUNDATION']);
  const record = restorePlan(fixture, next.plans.SYNTHETIC, person);
  assert.equal(planProgress(record.plan, next.model.snapshot(person)).done, 1);
  next.plans.SYNTHETIC.plan.coverageAfter = 999;
  assert.equal(restorePlan(fixture, next.plans.SYNTHETIC, person).plan.coverageAfter, plan.coverageAfter);
  assert.equal(restoreProgress({ ...fixture, asOf: '2027-01-01' }, storage).model.snapshot(person).simulated.length, 0);
  value = '{broken'; assert.equal(restoreProgress(fixture, storage).model.snapshot(person).simulated.length, 0);
  assert.equal(restorePlan(fixture, { plan: { steps: 5 } }, person), null);
  assert.equal(saveProgress(fixture, model, restored, { setItem: () => { throw new Error('quota'); } }), false);
});

test('HTTP exposes both workflows and validates inputs without exposing credentials', async t => {
  const provider = createStructuredProvider({ config: readConfig({}) });
  const server = createAppServer({ data, recommender: createRecommender({ provider }), workflows: createWorkflows({ data, provider }) });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
  const url = `http://127.0.0.1:${server.address().port}`;
  const post = (path, body) => fetch(url + path, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  assert.ok((await (await post('/api/development-plan', { employeeId: 'E0005' })).json()).plan.steps.length);
  assert.ok((await (await post('/api/hr/improve-activity', { eventId: 'EV_005', brief: '' })).json()).draft.agenda.length);
  assert.equal((await post('/api/development-plan', { employeeId: 'E0005', options: { maxSteps: 99 } })).status, 400);
  assert.equal((await post('/api/hr/improve-activity', { eventId: 'EV_001', brief: '' })).status, 400);
  for (const path of ['/workshop-ui.mjs', '/local-progress.mjs', '/development.mjs']) assert.equal((await fetch(url + path)).status, 200);
  assert.equal((await fetch(url + '/.env.local')).status, 404);
});

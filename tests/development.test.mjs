test('adding just a key enables defaults and hot reload; disabled setting still wins', t => {
  const directory = mkdtempSync(join(tmpdir(), 'career-config-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const file = join(directory, '.env.local'), config = configReader(file, {});
  const provider = createStructuredProvider({ config });
  assert.equal(provider.status().ready, false);
  writeFileSync(file, 'OPENAI_API_KEY=test-only-not-real');
  assert.equal(provider.status().ready, true);
  assert.equal(config().model, 'gpt-4.1-mini');
  assert.equal(config().baseUrl, 'https://api.openai.com/v1');
  assert.ok(!JSON.stringify(provider.status()).includes('test-only'));
  writeFileSync(file, 'OPENAI_API_KEY=test-only-not-real\nAI_ENABLED=false');
  assert.equal(provider.status().ready, false);
});

test('quest unlocks prerequisite chain, enforces caps, and never mutates source', () => {
  const before = JSON.stringify(fixture), model = createModel(fixture), state = model.snapshot(person);
  const paths = buildDevelopmentPaths(fixture, state, { weeklyHours: 4, maxSteps: 4 });
  const plan = paths[0];
  assert.deepEqual(plan.steps.map(s => s.event_id), ['FOUNDATION', 'ADVANCED']);
  assert.equal(plan.steps[1].prerequisites[0].level, 3);
  assert.equal(planProgress(plan, state).done, 0);
  assert.equal(model.complete(person.employee_id, 'ADVANCED'), false);
  assert.equal(model.complete(person.employee_id, 'FOUNDATION'), true);
  assert.equal(planProgress(plan, model.snapshot(person)).done, 1);
  assert.equal(model.complete(person.employee_id, 'ADVANCED'), true);
  assert.equal(planProgress(plan, model.snapshot(person)).done, 2);
  assert.equal(model.snapshot(person).coverage, plan.coverageAfter);
  model.setGoal(person.employee_id, 'Data Analyst', 'Middle');
  assert.equal(planProgress(plan, model.snapshot(person)).valid, false);
  assert.equal(JSON.stringify(fixture), before);
  assert.ok(plan.statChanges.every(s => s.after <= 5));
});

test('scheduled steps cannot start before previous step ends; weekly load changes estimates', () => {
  const sample = structuredClone(fixture);
  sample.events[0].format = 'online'; sample.events[0].upcoming_sessions = ['2026-10-02'];
  let paths = buildDevelopmentPaths(sample, createModel(sample).snapshot(sample.employees[0]));
  assert.deepEqual(paths[0].steps.map(s => s.event_id), ['FOUNDATION']);
  sample.events[0].upcoming_sessions.push('2026-10-10');
  paths = buildDevelopmentPaths(sample, createModel(sample).snapshot(sample.employees[0]));
  assert.deepEqual(paths[0].steps.map(s => s.event_id), ['FOUNDATION', 'ADVANCED']);
  assert.ok(paths[0].steps[1].start >= paths[0].steps[0].end);
  const slow = buildDevelopmentPaths(fixture, createModel(fixture).snapshot(person), { weeklyHours: 1 })[0];
  assert.ok(slow.end > paths[0].end);
});


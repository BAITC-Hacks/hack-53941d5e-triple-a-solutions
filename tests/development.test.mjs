test('every dataset path is playable in order with monotonic coverage and honest progress', () => {
  const source = JSON.stringify(data), model = createModel(data);
  let plans = 0;
  for (const employee of data.employees) {
    const plan = buildDevelopmentPaths(data, model.snapshot(employee))[0];
    if (!plan) continue;
    plans++;
    const simulation = createModel(data);
    for (const [i, step] of plan.steps.entries()) {
      assert.equal(planProgress(plan, simulation.snapshot(employee)).done, i);
      assert.equal(simulation.complete(employee.employee_id, step.event_id), true);
      assert.equal(step.coverageAfter, simulation.snapshot(employee).coverage);
      assert.ok(step.coverageAfter >= step.coverageBefore);
      if (i) assert.ok(step.start >= plan.steps[i - 1].end);
    }
  }
  assert.ok(plans > 0); assert.equal(JSON.stringify(data), source);
});

test('AI cannot invent plan steps, reorder prerequisites or replace numerical gains', () => {
  const paths = buildDevelopmentPaths(fixture, createModel(fixture).snapshot(person));
  const answer = planAnswer(paths[0]);
  answer.coverageAfter = 100; answer.steps[0].impact = [{ after: 999 }];
  const result = validatePlanAnswer(answer, paths);
  assert.equal(result.coverageAfter, paths[0].coverageAfter);
  assert.deepEqual(result.steps[0].impact, paths[0].steps[0].impact);
  answer.steps.reverse(); assert.throws(() => validatePlanAnswer(answer, paths));
});

test('HR drafts cite available aggregate evidence, respect time budget, and cannot change gains', () => {
  const before = JSON.stringify(data);
  for (const event of data.events.filter(e => !e.mandatory)) {
    const ctx = activityContext(data, event.event_id), draft = baselineActivityDraft(ctx);
    assert.deepEqual(validateHrAnswer(draft, ctx), draft);
    for (const person of data.employees) assert.ok(!JSON.stringify(ctx).includes(person.full_name));
    const invented = structuredClone(draft); invented.improvements[0].evidence_ids = ['fake'];
    assert.throws(() => validateHrAnswer(invented, ctx));
    const overtime = structuredClone(draft); overtime.agenda[0].minutes += 5000;
    assert.throws(() => validateHrAnswer(overtime, ctx));
    const foreignSkill = structuredClone(draft); foreignSkill.agenda[0].skill_ids = ['FAKE'];
    assert.throws(() => validateHrAnswer(foreignSkill, ctx));
    draft.develops_skills = [{ gain: 999 }];
    assert.equal(validateHrAnswer(draft, ctx).develops_skills, undefined);
  }
  assert.throws(() => activityContext(data, 'EV_001'));
  assert.equal(JSON.stringify(data), before);
});

